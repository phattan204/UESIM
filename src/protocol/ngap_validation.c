/* ============== IE Validation ============== */

ngap_validation_result_t ngap_validate_mandatory_ie(const uint8_t* data, size_t length,
                                                    uint32_t ie_id,
                                                    ngap_validation_context_t* ctx) {
    if (data == NULL) {
        return NGAP_VALIDATION_ERROR_NULL_POINTER;
    }
    
    /* Simple scan for IE ID (simplified - real NGAP uses ASN.1 PER encoding) */
    for (size_t offset = 0; offset + 4 <= length; ) {
        uint32_t found_ie_id = (uint32_t)data[offset] | 
                               ((uint32_t)data[offset + 1] << 8);
        
        if (found_ie_id == ie_id) {
            return NGAP_VALIDATION_OK;  /* Found */
        }
        
        /* Skip to next IE (simplified) */
        offset += 4;
    }
    
    ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_MANDATORY_IE, ie_id,
                             "Mandatory IE not found");
    return NGAP_VALIDATION_ERROR_MANDATORY_IE;
}

ngap_validation_result_t ngap_validate_criticality(uint8_t criticality,
                                                    ngap_validation_context_t* ctx) {
    switch (criticality) {
        case NGAP_CRITICALITY_REJECT:
        case NGAP_CRITICALITY_IGNORE:
        case NGAP_CRITICALITY_NOTIFY:
            return NGAP_VALIDATION_OK;
            
        default:
            if (ctx != NULL) {
                ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_CRITICALITY, 0,
                                         "Invalid criticality value");
            }
            return NGAP_VALIDATION_ERROR_CRITICALITY;
    }
}

ngap_validation_result_t ngap_validate_ie_length(uint16_t actual_len, uint16_t expected_len,
                                                  uint16_t min_len, uint16_t max_len) {
    if (expected_len > 0) {
        if (actual_len != expected_len) {
            return NGAP_VALIDATION_ERROR_IE_LENGTH;
        }
    } else {
        if (actual_len < min_len || actual_len > max_len) {
            return NGAP_VALIDATION_ERROR_IE_LENGTH;
        }
    }
    return NGAP_VALIDATION_OK;
}


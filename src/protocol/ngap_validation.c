/* ============== Initialization ============== */

ngap_validation_result_t ngap_validation_init(const ngap_validation_config_t* config) {
    if (config != NULL) {
        memcpy(&g_config, config, sizeof(ngap_validation_config_t));
    } else {
        ngap_validation_get_default_config(&g_config);
    }
    g_initialized = true;
    return NGAP_VALIDATION_OK;
}

void ngap_validation_get_default_config(ngap_validation_config_t* config) {
    if (config == NULL) return;
    
    config->check_mandatory_ie = true;
    config->check_criticality = true;
    config->check_value_ranges = true;
    config->strict_mode = false;
    config->allow_unknown_ie = true;
    config->max_message_size = NGAP_MAX_PDU_SIZE;
    config->max_nested_depth = NGAP_MAX_NESTED_IES;
}

void ngap_validation_cleanup(void) {
    memset(&g_config, 0, sizeof(g_config));
    g_initialized = false;
}

/* ============== Validation Context Helpers ============== */

void ngap_validation_context_init(ngap_validation_context_t* ctx) {
    if (ctx == NULL) return;
    memset(ctx, 0, sizeof(ngap_validation_context_t));
    ctx->result = NGAP_VALIDATION_OK;
}

void ngap_validation_set_error(ngap_validation_context_t* ctx,
                                ngap_validation_result_t result,
                                uint32_t ie_id,
                                const char* message) {
    if (ctx == NULL) return;
    
    ctx->result = result;
    ctx->error_ie_id = ie_id;
    if (message != NULL) {
        strncpy(ctx->error_message, message, sizeof(ctx->error_message) - 1);
        ctx->error_message[sizeof(ctx->error_message) - 1] = '\0';
    }
}

void ngap_validation_context_print(const ngap_validation_context_t* ctx) {
    if (ctx == NULL) return;
    
    printf("NGAP Validation Context:\n");
    printf("  Result: %s\n", ngap_validation_result_to_string(ctx->result));
    printf("  Validated Bytes: %u\n", ctx->validated_bytes);
    printf("  IE Count: %u\n", ctx->ie_count);
    if (ctx->result != NGAP_VALIDATION_OK) {
        printf("  Error IE ID: %u (%s)\n", 
               ctx->error_ie_id, ngap_ie_id_to_string(ctx->error_ie_id));
        printf("  Error Message: %s\n", ctx->error_message);
    }
}

/* ============== PDU Validation ============== */

ngap_validation_result_t ngap_validate_pdu_header(const uint8_t* data, size_t length,
                                                    ngap_validation_context_t* ctx) {
    ngap_validation_context_t local_ctx;
    if (ctx == NULL) {
        ctx = &local_ctx;
        ngap_validation_context_init(ctx);
    }
    
    if (data == NULL) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_NULL_POINTER, 0, "NULL data pointer");
        return NGAP_VALIDATION_ERROR_NULL_POINTER;
    }
    
    if (length < NGAP_MIN_HEADER_SIZE) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_BUFFER_TOO_SMALL, 0, 
                                 "Buffer too small for header");
        return NGAP_VALIDATION_ERROR_BUFFER_TOO_SMALL;
    }
    
    /* Check NGAP message discriminator (0x00 for NGAP) */
    if (data[0] != 0x00) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_MESSAGE_TYPE, 0,
                                 "Invalid NGAP discriminator");
        return NGAP_VALIDATION_ERROR_MESSAGE_TYPE;
    }
    
    ctx->validated_bytes = 4;
    ctx->ie_count = 0;
    
    return NGAP_VALIDATION_OK;
}

ngap_validation_result_t ngap_validate_pdu(const uint8_t* data, size_t length,
                                            ngap_validation_context_t* ctx) {
    ngap_validation_context_t local_ctx;
    if (ctx == NULL) {
        ctx = &local_ctx;
        ngap_validation_context_init(ctx);
    }
    
    if (data == NULL) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_NULL_POINTER, 0, "NULL data pointer");
        return NGAP_VALIDATION_ERROR_NULL_POINTER;
    }
    
    if (length > g_config.max_message_size) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_LENGTH, 0, "Message exceeds max size");
        return NGAP_VALIDATION_ERROR_LENGTH;
    }
    
    /* Validate header first */
    ngap_validation_result_t result = ngap_validate_pdu_header(data, length, ctx);
    if (result != NGAP_VALIDATION_OK) {
        return result;
    }
    
    /* Extract procedure code and message type from header */
    uint8_t procedure_code = data[1];
    uint8_t message_type = data[2];
    
    if (!ngap_is_valid_procedure_code(procedure_code)) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_PROCEDURE_CODE, 0,
                                 "Invalid procedure code");
        return NGAP_VALIDATION_ERROR_PROCEDURE_CODE;
    }
    
    /* Validate minimum length */
    size_t min_len = ngap_get_min_message_length((ngap_message_type_t)message_type);
    if (length < min_len) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_LENGTH, 0,
                                 "Message shorter than minimum");
        return NGAP_VALIDATION_ERROR_LENGTH;
    }
    
    /* Message-specific validation */
    const uint8_t* payload = data + 4;
    size_t payload_len = length - 4;
    
    switch (message_type) {
        case NGAP_MSG_NG_SETUP_REQUEST:
            return ngap_validate_ng_setup_request(payload, payload_len, ctx);
            
        case NGAP_MSG_NG_SETUP_RESPONSE:
            return ngap_validate_ng_setup_response(payload, payload_len, ctx);
            
        case NGAP_MSG_INITIAL_UE_MESSAGE:
            return ngap_validate_initial_ue_message(payload, payload_len, ctx);
            
        case NGAP_MSG_INITIAL_CONTEXT_SETUP_REQUEST:
            return ngap_validate_initial_context_setup_request(payload, payload_len, ctx);
            
        case NGAP_MSG_PDU_SESSION_SETUP_REQUEST:
            return ngap_validate_pdu_session_setup_request(payload, payload_len, ctx);
            
        case NGAP_MSG_ERROR_INDICATION:
            return ngap_validate_error_indication(payload, payload_len, ctx);
            
        default:
            /* Unknown message type - skip specific validation */
            ctx->validated_bytes = length;
            return NGAP_VALIDATION_OK;
    }
}

ngap_validation_result_t ngap_validate_pdu_length(size_t length, 
                                                    ngap_message_type_t expected_type) {
    size_t min_len = ngap_get_min_message_length(expected_type);
    if (length < min_len) {
        return NGAP_VALIDATION_ERROR_LENGTH;
    }
    
    if (length > NGAP_MAX_PDU_SIZE) {
        return NGAP_VALIDATION_ERROR_LENGTH;
    }
    
    return NGAP_VALIDATION_OK;
}

/* ============== Message-Specific Validation ============== */

ngap_validation_result_t ngap_validate_ng_setup_request(const uint8_t* data, size_t length,
                                                         ngap_validation_context_t* ctx) {
    if (data == NULL || length < 10) {
        ngap_validation_set_error(ctx, NGAP_VALIDATION_ERROR_LENGTH, 0,
                                 "NG Setup Request too short");
        return NGAP_VALIDATION_ERROR_LENGTH;
    }
    
    /* Check mandatory IEs: Global RAN Node ID, gNB Name, TAC, etc. */
    if (g_config.check_mandatory_ie) {
        ngap_validation_result_t result = ngap_validate_mandatory_ie(data, length,
                                                                     NGAP_IE_GLOBAL_RAN_NODE_ID, ctx);
        if (result != NGAP_VALIDATION_OK) {
            return result;
        }
    }
    
    ctx->validated_bytes = length;
    return NGAP_VALIDATION_OK;
}

